/**
 * Android build pipeline.
 *
 * Generates a complete, conventional Android Gradle project around the product's
 * web build, then drives Gradle to compile, package and sign a real APK, and
 * verifies the signature with apksigner before the artifact is recorded.
 *
 * Architecture note (see docs/3D-PIPELINE.md for the full rationale): products
 * are authored once as TypeScript/WebGL and hosted on Android inside a hardened
 * WebView served through WebViewAssetLoader, which gives the page a secure
 * https origin — so service workers, storage and WebGL 2.0 behave exactly as
 * they do in the preview. The preview and the APK therefore run the *same*
 * bytes, which is what makes "the preview is the product" true rather than a
 * convenient claim.
 *
 * When the toolchain is incomplete the build fails with a TOOLCHAIN_MISSING
 * diagnostic listing precisely what to install. It never emits a placeholder
 * file with an .apk extension.
 */

export interface AndroidBuildResult {
  readonly build: BuildRecord;
  readonly artifact: BuildArtifact | null;
  readonly succeeded: boolean;
  readonly toolchain: AndroidToolchain;
  readonly diagnostics: readonly BuildDiagnostic[];
}

export interface AndroidBuildOptions {
  readonly mode?: BuildMode;
  readonly signal?: AbortSignal;
  /** Gradle must reach the Google and Maven Central repositories to resolve the AGP. */
  readonly allowNetwork?: boolean;
}

function javaPackagePath(applicationId: string): string {
  return applicationId.split('.').join('/');
}

