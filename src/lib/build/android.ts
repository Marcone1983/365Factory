interface SigningPlan {
  readonly keystorePath: string;
  readonly storePassword: string;
  readonly keyAlias: string;
  readonly keyPassword: string;
  readonly kind: 'release' | 'generated-debug';
}

/**
 * Resolves signing material. A configured release keystore is used as-is; its
 * secrets are passed to Gradle through the environment and never written into
 * the generated build files. Otherwise a project-local keystore is generated
 * with keytool and the artifact is clearly labelled as debug-signed.
 */
async function resolveSigning(project: Project, toolchain: AndroidToolchain, build: BuildRecord): Promise<SigningPlan> {
  const cfg = config();
  if (toolchain.keystore.available && cfg.ANDROID_KEYSTORE_PATH) {
    return {
      keystorePath: cfg.ANDROID_KEYSTORE_PATH,
      storePassword: cfg.ANDROID_KEYSTORE_PASSWORD ?? '',
      keyAlias: cfg.ANDROID_KEY_ALIAS ?? '',
      keyPassword: cfg.ANDROID_KEY_PASSWORD ?? '',
      kind: 'release',
    };
  }

  const keystoreDir = path.join(project.workspacePath, 'build', 'signing');
  ensureDir(keystoreDir);
  const keystorePath = path.join(keystoreDir, 'debug.keystore');
  const password = 'adafdebug';
  const alias = 'adafdebug';

  if (!fs.existsSync(keystorePath)) {
    appendBuildLog(build, '\n== generating project debug keystore ==\n');
    const result = await runSandboxed({
      executable: 'keytool',
      args: [
        '-genkeypair', '-v',
        '-keystore', keystorePath,
        '-storepass', password,
        '-keypass', password,
        '-alias', alias,
        '-keyalg', 'RSA', '-keysize', '2048', '-validity', '10000',
        '-dname', `CN=${project.name.replace(/[^\w .-]/g, '')}, OU=Autonomous Daily App Factory, O=Factory, C=US`,
      ],
      cwd: keystoreDir,
      jailRoot: project.workspacePath,
      timeoutMs: 120_000,
    });
    appendBuildLog(build, `${result.stdout}${result.stderr}\n`);
    if (result.exitCode !== 0 || !fs.existsSync(keystorePath)) {
      throw new Error(`keytool failed to generate a debug keystore (exit ${result.exitCode}): ${result.stderr.slice(0, 500)}`);
    }
  }

  return { keystorePath, storePassword: password, keyAlias: alias, keyPassword: password, kind: 'generated-debug' };
}

export interface GeneratedAndroidProject {
  readonly root: string;
  readonly files: readonly string[];
}

/** Writes the Gradle project. Exported so the IDE can show what will be built. */
export function generateAndroidProject(project: Project, signing: SigningPlan, mode: BuildMode): GeneratedAndroidProject {
  const cfg = config();
  const root = path.join(project.workspacePath, 'build', 'android');
  const appDir = path.join(root, 'app');
  const mainDir = path.join(appDir, 'src', 'main');
  const files: string[] = [];

  const write = (relative: string, contents: string | Buffer): void => {
    const target = path.join(root, relative);
    ensureDir(path.dirname(target));
    fs.writeFileSync(target, contents);
    files.push(relative);
  };

  const brand = project.brand as { background?: string; primary?: string };
  write('settings.gradle.kts', settingsGradle(project.slug));
  write('build.gradle.kts', rootBuildGradle(cfg.ANDROID_GRADLE_PLUGIN_VERSION));
  write('gradle.properties', gradleProperties());
  write('app/build.gradle.kts', appBuildGradle(project, signing, mode));
  write('app/proguard-rules.pro', proguardRules());
  write('app/src/main/AndroidManifest.xml', androidManifest(project));
  write(`app/src/main/java/${javaPackagePath(project.applicationId)}/MainActivity.java`, mainActivity(project));
  write('app/src/main/res/values/strings.xml', stringsXml(project));
  write('app/src/main/res/values/themes.xml', themesXml(brand.background ?? '#0b0f1a', brand.primary ?? '#6ea8fe'));
  write('app/src/main/res/drawable/splash_layer.xml', splashLayerXml());
  write('app/src/main/res/xml/data_extraction_rules.xml', dataExtractionRules());

  // Web build output becomes the APK's asset payload.
  const webBuild = path.join(project.workspacePath, 'build', 'web');
  const assetsWww = path.join(mainDir, 'assets', 'www');
  fs.rmSync(assetsWww, { recursive: true, force: true });
  ensureDir(assetsWww);
  if (!fs.existsSync(path.join(webBuild, 'index.html'))) {
    throw new Error('No web build output found: run the web build before packaging the APK.');
  }
  fs.cpSync(webBuild, assetsWww, { recursive: true });

  // Launcher icons and splash come from the generated asset set.
  const generatedAssets = path.join(project.workspacePath, 'assets', 'android');
  if (fs.existsSync(generatedAssets)) {
    for (const entry of fs.readdirSync(generatedAssets, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue;
      const from = path.join(generatedAssets, entry.name);
      const to = path.join(mainDir, 'res', entry.name);
      ensureDir(to);
      fs.cpSync(from, to, { recursive: true, force: true });
    }
  }
  const splashTarget = path.join(mainDir, 'res', 'drawable', 'splash.png');
  if (!fs.existsSync(splashTarget)) {
    throw new Error('Launcher splash asset is missing: generate brand assets before packaging the APK.');
  }

  return { root, files };
}

function parseGradleDiagnostics(output: string): BuildDiagnostic[] {
  const diagnostics: BuildDiagnostic[] = [];
  const javac = /^(\/.*?\.java):(\d+):\s+(error|warning):\s+(.*)$/gm;
  let match = javac.exec(output);
  while (match) {
    diagnostics.push({
      severity: match[3] === 'error' ? 'error' : 'warning',
      file: match[1],
      line: Number.parseInt(match[2] ?? '0', 10),
      message: match[4] ?? '',
    });
    match = javac.exec(output);
  }
  const gradleError = /^(?:FAILURE: |\* What went wrong:\n)(.*)$/gm;
  let gm = gradleError.exec(output);
  while (gm) {
    diagnostics.push({ severity: 'error', message: (gm[1] ?? '').trim() });
    gm = gradleError.exec(output);
  }
  return diagnostics;
}

export async function buildAndroidApk(project: Project, options: AndroidBuildOptions = {}): Promise<AndroidBuildResult> {
  const cfg = config();
  const mode = options.mode ?? 'release';
  const toolchain = androidToolchain(true);
  const build = startBuild({
    project,
    target: 'android-apk',
    mode,
    toolchain: {
      java: toolchain.java.version ?? null,
      gradle: toolchain.gradle.version ?? null,
      sdk: toolchain.sdk.path ?? null,
      buildTools: toolchain.buildTools.version ?? null,
      compileSdk: cfg.ANDROID_COMPILE_SDK,
      agp: cfg.ANDROID_GRADLE_PLUGIN_VERSION,
    },
  });

  if (!toolchain.ready) {
    const detail = [
      'The Android toolchain is incomplete, so no APK can be produced.',
      `Missing: ${toolchain.missing.join(', ')}.`,
      toolchain.java.detail,
      toolchain.gradle.detail,
      toolchain.sdk.detail,
      toolchain.platform.detail,
      toolchain.buildTools.detail,
    ].join('\n');
    appendBuildLog(build, `\n== TOOLCHAIN_MISSING ==\n${detail}\n`);
    const finished = finishBuild(build, {
      status: 'FAILED',
      exitCode: null,
      errorSummary: `TOOLCHAIN_MISSING: ${toolchain.missing.join(', ')}`,
      diagnostics: [{ severity: 'error', code: 'TOOLCHAIN_MISSING', message: detail }],
    });
    log.warn('android build refused: toolchain incomplete', { projectId: project.id, missing: toolchain.missing });
    return { build: finished, artifact: null, succeeded: false, toolchain, diagnostics: finished.diagnostics };
  }

  try {
    const signing = await resolveSigning(project, toolchain, build);
    appendBuildLog(build, `\n== generating gradle project (signing: ${signing.kind}) ==\n`);
    const generated = generateAndroidProject(project, signing, mode);
    appendBuildLog(build, `${generated.files.length} project files written to ${generated.root}\n`);

    const task = mode === 'release' ? ':app:assembleRelease' : ':app:assembleDebug';
    appendBuildLog(build, `\n== gradle ${task} ==\n`);

    const result = await runSandboxed({
      executable: 'gradle',
      executablePath: toolchain.gradle.path,
      args: [task, '--no-daemon', '--console=plain', '--stacktrace'],
      cwd: generated.root,
      jailRoot: project.workspacePath,
      timeoutMs: cfg.BUILD_TIMEOUT_MS,
      // Gradle must reach the Google and Maven Central repositories to resolve
      // the Android Gradle Plugin and AndroidX. This is the one build step that
      // legitimately needs egress.
      allowNetwork: options.allowNetwork ?? true,
      env: {
        ADAF_KEYSTORE_PASSWORD: signing.storePassword,
        ADAF_KEY_ALIAS: signing.keyAlias,
        ADAF_KEY_PASSWORD: signing.keyPassword,
      },
      signal: options.signal,
      onOutput: (chunk) => appendBuildLog(build, chunk),
    });

    const output = `${result.stdout}\n${result.stderr}`;
    const diagnostics = parseGradleDiagnostics(output);

    if (result.exitCode !== 0) {
      const finished = finishBuild(build, {
        status: result.timedOut ? 'CANCELLED' : 'FAILED',
        exitCode: result.exitCode,
        errorSummary: result.timedOut
          ? `Gradle exceeded the ${cfg.BUILD_TIMEOUT_MS}ms build timeout.`
          : (diagnostics.find((d) => d.severity === 'error')?.message ?? 'Gradle failed; see the build log.'),
        diagnostics,
      });
      return { build: finished, artifact: null, succeeded: false, toolchain, diagnostics };
    }

    const apkPath = findApk(generated.root, mode);
    if (!apkPath) {
      const finished = finishBuild(build, {
        status: 'FAILED',
        exitCode: 0,
        errorSummary: 'Gradle reported success but no APK was found in the expected output directory.',
        diagnostics,
      });
      return { build: finished, artifact: null, succeeded: false, toolchain, diagnostics };
    }

    const publishedPath = path.join(project.workspacePath, 'artifacts', `${project.slug}-${project.versionName}-${mode}.apk`);
    ensureDir(path.dirname(publishedPath));
    fs.copyFileSync(apkPath, publishedPath);

    const verification = await verifyApkSignature(project, publishedPath, toolchain, options.signal);
    appendBuildLog(build, `\n== apksigner verify ==\n${verification.output}\n`);
    if (!verification.verified) {
      fs.rmSync(publishedPath, { force: true });
      const finished = finishBuild(build, {
        status: 'FAILED',
        exitCode: 1,
        errorSummary: `Signature verification failed: ${verification.output.slice(0, 500)}`,
        diagnostics,
      });
      return { build: finished, artifact: null, succeeded: false, toolchain, diagnostics };
    }

    const artifact = recordArtifact({
      build,
      kind: 'apk',
      absolutePath: publishedPath,
      signed: true,
      signatureInfo: { ...verification.schemes, signing: signing.kind, verifiedBy: 'apksigner' },
    });
    appendBuildLog(build, `\nAPK ready: ${artifact.filename} (${artifact.bytes} bytes, sha256 ${artifact.sha256})\n`);

    const finished = finishBuild(build, { status: 'SUCCEEDED', exitCode: 0, diagnostics });
    log.info('android build succeeded', { projectId: project.id, bytes: artifact.bytes, signing: signing.kind });
    return { build: finished, artifact, succeeded: true, toolchain, diagnostics };
  } catch (error) {
    const message = (error as Error).message;
    appendBuildLog(build, `\nBUILD FAILED: ${message}\n`);
    const finished = finishBuild(build, {
      status: 'FAILED',
      exitCode: 1,
      errorSummary: message,
      diagnostics: [{ severity: 'error', message }],
    });
    return { build: finished, artifact: null, succeeded: false, toolchain, diagnostics: finished.diagnostics };
  }
}

function findApk(root: string, mode: BuildMode): string | null {
  const candidates = [
    path.join(root, 'app', 'build', 'outputs', 'apk', mode, `app-${mode}.apk`),
    path.join(root, 'app', 'build', 'outputs', 'apk', mode),
  ];
  for (const candidate of candidates) {
    if (!fs.existsSync(candidate)) continue;
    const stats = fs.statSync(candidate);
    if (stats.isFile()) return candidate;
    const apk = fs.readdirSync(candidate).find((name) => name.endsWith('.apk'));
    if (apk) return path.join(candidate, apk);
  }
  return null;
}

export interface SignatureVerification {
  readonly verified: boolean;
  readonly output: string;
  readonly schemes: Record<string, boolean>;
}

export async function verifyApkSignature(
  project: Project,
  apkPath: string,
  toolchain: AndroidToolchain,
  signal?: AbortSignal,
): Promise<SignatureVerification> {
  if (!toolchain.apksigner.available || !toolchain.apksigner.path) {
    return { verified: false, output: 'apksigner is not available; the signature could not be verified.', schemes: {} };
  }
  const result = await runSandboxed({
    executable: 'apksigner',
    executablePath: toolchain.apksigner.path,
    args: ['verify', '--verbose', '--print-certs', apkPath],
    cwd: path.dirname(apkPath),
    jailRoot: project.workspacePath,
    timeoutMs: 120_000,
    signal,
  });
  const output = `${result.stdout}\n${result.stderr}`.trim();
  const schemes: Record<string, boolean> = {};
  for (const scheme of ['v1', 'v2', 'v3', 'v4']) {
    const match = new RegExp(`Verified using ${scheme} scheme[^:]*:\\s*(true|false)`, 'i').exec(output);
    if (match) schemes[scheme] = match[1]?.toLowerCase() === 'true';
  }
  return { verified: result.exitCode === 0 && /Verifies/i.test(output), output, schemes };
}

function escapeXml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}
